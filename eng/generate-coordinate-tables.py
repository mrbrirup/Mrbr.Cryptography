"""Generate immutable GF(256) log tables for PUBLIC interpolation coordinates.

The polynomial model is unchanged: carry-less multiplication modulo 0x11B.
Generator 0x03 must visit all 255 nonzero elements before returning to one.
No third-party dependencies. Run with --check to verify the committed table.
"""
import argparse
from pathlib import Path


def multiply(left, right):
    product = 0
    for bit in range(8):
        if right & (1 << bit):
            product ^= left << bit
    for degree in range(14, 7, -1):
        if product & (1 << degree):
            product ^= 0x11B << (degree - 8)
    return product


def render_table(name, values):
    lines = []
    for start in range(0, len(values), 16):
        lines.append("        " + ", ".join(f"0x{v:02X}" for v in values[start:start + 16]) + ",")
    return f"    private static ReadOnlySpan<byte> {name} =>\n    [\n" + "\n".join(lines) + "\n    ];\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    options = parser.parse_args()
    powers, logarithms = [], [0] * 256  # log(0) is unused, not mathematically defined.
    value = 1
    for exponent in range(255):
        assert value != 0 and value not in powers
        logarithms[value] = exponent
        powers.append(value)
        value = multiply(value, 0x03)
    assert value == 1 and len(set(powers)) == 255
    content = """// Generated by eng/generate-coordinate-tables.py; do not edit by hand.
// ReadOnlySpan literals use assembly data, not allocated managed arrays.
// These tables must only be indexed by PUBLIC coordinate-derived values.
namespace Mrbr.Cryptography.Internal;

internal static partial class LagrangeWeights
{
"""
    content += render_table("Logarithms", logarithms)
    # Two periods avoid modulo in the special two-share quotient.
    content += "\n" + render_table("Exponents", powers + powers) + "}\n"
    target = Path(__file__).resolve().parents[1] / "src/Mrbr.Cryptography/Internal/LagrangeWeights.Tables.cs"
    if options.check:
        if target.read_text(encoding="utf-8") != content:
            raise SystemExit("Coordinate tables differ; rerun the generator.")
        print("Coordinate tables match; generator 0x03 has order 255.")
    else:
        target.write_text(content, encoding="utf-8", newline="\n")
        print(target)


if __name__ == "__main__":
    main()
